/**
 * Tests for the pieces of setup that decide which proxy runs on the user's
 * machine (security review 2026-10-17, SC-2 and SC-9): the `claude mcp add`
 * registration, the shipped `.mcp.json`, the package's `repository` field,
 * the version check behind the upgrade hint, and `--version`, which a manual
 * registration pins. Every registration names the version that wrote it;
 * `npx @pharaoh-so/mcp@latest` is the deliberate upgrade. Also what setup
 * tells someone with no `claude` CLI on PATH, such as a desktop app user,
 * whose built-in Claude Code isn't on PATH.
 */
import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { claudeCliMissing, hasClaude, runSetup } from "../src/setup.js";
import { fetchLatestVersion, getPackageVersion, isNewerVersion } from "../src/version.js";

const PKG_ROOT = join(__dirname, "..");

/** Collect what setup prints to stderr (restored by `vi.restoreAllMocks`). */
function captureStderr(): { text: () => string } {
	const chunks: string[] = [];
	vi.spyOn(process.stderr, "write").mockImplementation((chunk) => {
		chunks.push(String(chunk));
		return true;
	});
	return { text: () => chunks.join("") };
}

describe("SC-2: the installed command is pinned to the running version", () => {
	let home: string;

	beforeEach(() => {
		home = mkdtempSync(join(tmpdir(), "pharaoh-setup-"));
		mkdirSync(join(home, ".claude"), { recursive: true });
	});

	afterEach(() => {
		vi.restoreAllMocks();
		rmSync(home, { recursive: true, force: true });
	});

	it("runSetup registers npx @pharaoh-so/mcp@<version> in user scope", () => {
		const calls: string[] = [];
		const claude = (args: string[]) => {
			calls.push(args.join(" "));
			return true;
		};

		expect(runSetup({ silent: true, home, claude })).toBe(true);

		const version = getPackageVersion();
		expect(version).toMatch(/^\d+\.\d+\.\d+$/);
		expect(calls).toEqual([
			"mcp remove pharaoh -s user",
			"mcp remove pharaoh -s project",
			`mcp add --scope user pharaoh -- npx @pharaoh-so/mcp@${version}`,
		]);
	});

	it("when `claude mcp add` fails, names the command to run by hand, not npx again", () => {
		const stderr = captureStderr();
		const claude = (args: string[]) => args[1] !== "add";

		expect(runSetup({ silent: true, home, claude })).toBe(false);

		expect(stderr.text()).toContain(
			`claude mcp add --scope user pharaoh -- npx @pharaoh-so/mcp@${getPackageVersion()}`,
		);
	});

	it("the shipped .mcp.json pins the same version (regenerated by `pnpm build`)", () => {
		const mcp = JSON.parse(readFileSync(join(PKG_ROOT, ".mcp.json"), "utf-8")) as {
			mcpServers: { pharaoh: { command: string; args: string[] } };
		};
		expect(mcp.mcpServers.pharaoh).toEqual({
			command: "npx",
			args: [`@pharaoh-so/mcp@${getPackageVersion()}`],
		});
	});

	// A manual registration pins what `--version` prints. Unhandled, the flag ran
	// setup: proxy mode on a pipe, and in a terminal a sign-in that deleted saved
	// credentials. PATH holds only node, so a regression reaches no `claude` CLI.
	it.each(["--version", "-v"])("%s prints the version and exits before setup", (flag) => {
		const tsx = createRequire(import.meta.url).resolve("tsx/cli");
		const res = spawnSync(process.execPath, [tsx, join(PKG_ROOT, "src", "index.ts"), flag], {
			input: "",
			encoding: "utf-8",
			timeout: 20_000,
			env: { HOME: home, PATH: dirname(process.execPath), PHARAOH_MCP_DISABLE_BROWSER: "1" },
		});
		const { version } = JSON.parse(readFileSync(join(PKG_ROOT, "package.json"), "utf-8"));

		expect(res.stdout).toBe(`${version}\n`);
		expect(res.status).toBe(0);
		expect(readdirSync(home)).toEqual([".claude"]);
	});
});

// Breaks when: setup sends someone without the `claude` CLI to the desktop app
// download (which they may already have), or stops naming the CLI install.
describe("no `claude` CLI on PATH (the desktop app's built-in one isn't)", () => {
	let home: string;
	const savedPath = process.env.PATH;

	beforeEach(() => {
		home = mkdtempSync(join(tmpdir(), "pharaoh-setup-no-cli-"));
		// The desktop app creates ~/.claude; only the CLI is missing.
		mkdirSync(join(home, ".claude"), { recursive: true });
		mkdirSync(join(home, "bin"));
		process.env.PATH = join(home, "bin");
	});

	afterEach(() => {
		process.env.PATH = savedPath;
		vi.restoreAllMocks();
		rmSync(home, { recursive: true, force: true });
	});

	it("runSetup stops and points at the Claude Code CLI install, not the desktop app download", () => {
		const stderr = captureStderr();

		expect(runSetup({ home })).toBe(false);

		expect(stderr.text()).toContain("https://code.claude.com/docs/en/setup");
		expect(stderr.text()).not.toContain("claude.ai/download");
	});

	it.skipIf(process.platform === "win32")(
		"finds a claude that starts where there is no `which` (minimal containers)",
		() => {
			writeFileSync(join(home, "bin", "claude"), "#!/bin/sh\necho 2.0.0\n", { mode: 0o755 });

			expect(hasClaude()).toBe(true);
		},
	);

	it.each([
		["darwin", "curl -fsSL https://claude.ai/install.sh | bash"],
		["win32", "irm https://claude.ai/install.ps1 | iex"],
	] as const)("on %s, gives `%s` at the end of its line, so a copy takes nothing more", (platform, command) => {
		expect(claudeCliMissing(platform).some((line) => line.endsWith(`: ${command}`))).toBe(true);
	});

	// main() runs only from a terminal, so the order is checked in its source.
	it("the interactive setup checks for the CLI before sign-in, and ends on a failed registration", () => {
		const main = readFileSync(join(PKG_ROOT, "src", "index.ts"), "utf-8");
		const interactive = main.slice(main.indexOf("if (isInteractive) {"));
		const at = (code: string) => interactive.indexOf(code);

		expect(interactive).toMatch(/if \(!hasClaude\(\)\) \{[^}]*process\.exit\(1\)/);
		expect(at("if (!hasClaude())")).toBeLessThan(at("deleteCredentials()"));
		expect(interactive).toMatch(/if \(!runSetup\([^)]*\)\)\s*\{?\s*process\.exit\(1\)/);
		expect(at("if (!runSetup(")).toBeLessThan(at("Pharaoh is ready"));
	});

	// The CLAUDE.md line is the user's file: asked about only here, never on a proxy start.
	it("offers the CLAUDE.md line once, in the interactive setup after registration", () => {
		const main = readFileSync(join(PKG_ROOT, "src", "index.ts"), "utf-8");
		const interactive = main.slice(
			main.indexOf("if (isInteractive) {"),
			main.indexOf("// ── Proxy mode"),
		);
		const at = (code: string) => interactive.indexOf(code);

		expect(main.match(/offerClaudeMdLine\(/g)).toHaveLength(1);
		expect(at("if (!runSetup(")).toBeLessThan(at("offerClaudeMdLine("));
		expect(at("offerClaudeMdLine(")).toBeLessThan(at("Pharaoh is ready"));
	});

	// uninstallClaudePlugin removes the CLAUDE.md line; on --logout it must not stand between the user and a credential wipe.
	it("--clean and --logout remove the CLAUDE.md line, and --logout deletes credentials first", () => {
		const main = readFileSync(join(PKG_ROOT, "src", "index.ts"), "utf-8");
		const branch = (opening: string) => {
			const start = main.indexOf(opening);
			return main.slice(start, main.indexOf("process.exit(0)", start));
		};
		expect(branch('if (args.includes("--clean")) {')).toContain("uninstallClaudePlugin();");
		const logout = branch("if (logout) {");
		expect(logout).toContain("uninstallClaudePlugin();");
		expect(logout.indexOf("deleteCredentials();")).toBeLessThan(
			logout.indexOf("uninstallClaudePlugin();"),
		);
	});
});

describe("SC-9: package.json names the repository that builds it", () => {
	it("repository names the standalone public source, so npm provenance verifies", () => {
		const pkg = JSON.parse(readFileSync(join(PKG_ROOT, "package.json"), "utf-8")) as {
			repository: { type: string; url: string; directory?: string };
		};
		expect(pkg.repository).toEqual({
			type: "git",
			url: "git+https://github.com/Pharaoh-so/pharaoh-mcp.git",
		});
	});
});

describe("upgrade hint — version comparison and the registry check", () => {
	it.each([
		["0.3.44", "0.3.43", true],
		["0.4.0", "0.3.99", true],
		["1.0.0", "0.9.9", true],
		["0.3.43", "0.3.43", false],
		["0.3.42", "0.3.43", false],
		["garbage", "0.3.43", false],
	])("isNewerVersion(%s, %s) is %s", (candidate, current, expected) => {
		expect(isNewerVersion(candidate, current)).toBe(expected);
	});

	it("returns the registry's latest version", async () => {
		const fetchImpl = (async () => ({
			ok: true,
			json: async () => ({ version: "9.9.9" }),
		})) as unknown as typeof fetch;

		await expect(fetchLatestVersion(fetchImpl)).resolves.toBe("9.9.9");
	});

	it("returns null, without throwing, when the registry is unreachable or answers oddly", async () => {
		const offline = (async () => {
			throw new Error("ENOTFOUND");
		}) as unknown as typeof fetch;
		const odd = (async () => ({ ok: true, json: async () => ({}) })) as unknown as typeof fetch;

		await expect(fetchLatestVersion(offline)).resolves.toBeNull();
		await expect(fetchLatestVersion(odd)).resolves.toBeNull();
	});
});
