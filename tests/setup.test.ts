describe("upgrade hint — version comparison and the registry check", () => {
	it.each([
		["0.3.44", "0.3.43", true],
		["0.4.0", "0.3.99", true],
		["1.0.0", "0.9.9", true],
		["0.3.43", "0.3.43", false],
		["0.3.42", "0.3.43", false],
		["garbage", "0.3.43", false],
	])("isNewerVersion(%s, %s) is %s", (candidate, current, expected) => {
		expect(isNewerVersion(candidate, current)).toBe(expected);
	});

	it("returns the registry's latest version", async () => {
		const fetchImpl = (async () => ({
			ok: true,
			json: async () => ({ version: "9.9.9" }),
		})) as unknown as typeof fetch;

		await expect(fetchLatestVersion(fetchImpl)).resolves.toBe("9.9.9");
	});

	it("returns null, without throwing, when the registry is unreachable or answers oddly", async () => {
		const offline = (async () => {
			throw new Error("ENOTFOUND");
		}) as unknown as typeof fetch;
		const odd = (async () => ({ ok: true, json: async () => ({}) })) as unknown as typeof fetch;

		await expect(fetchLatestVersion(offline)).resolves.toBeNull();
		await expect(fetchLatestVersion(odd)).resolves.toBeNull();
	});
});

it("explicit reset continues independent cleanup when the private installation record is broken", () => {
	const localRoot = join(home, "local-project");
	const localEntry = {
		command: "node",
		args: ["/managed/launcher-v1.mjs", "--install-scope", "local", "--install-root", localRoot],
	};
	mkdirSync(join(home, ".pharaoh"));
	mkdirSync(join(home, "empty-path"));
	writeFileSync(join(home, ".pharaoh", "client-installations.json"), "{broken");
	writeJson(join(home, ".claude.json"), {
		mcpServers: {
			pharaoh: { command: "npx", args: ["@pharaoh-so/mcp@0.3.50"] },
			other: { command: "keep-this-server" },
		},
		projects: {
			fixture: { disabledMcpServers: ["pharaoh", "other"] },
			[localRoot]: { mcpServers: { pharaoh: localEntry } },
		},
	});
	const result = cli(["--clean"], { path: join(home, "empty-path") });
	expect(result.status).toBe(1);
	expect(result.stderr).toContain("installation record could not be read");
	expect(readJson(join(home, ".claude.json"))).toEqual({
		mcpServers: { other: { command: "keep-this-server" } },
		projects: {
			fixture: { disabledMcpServers: ["other"] },
			[localRoot]: { mcpServers: { pharaoh: localEntry } },
		},
	});
});

it.each([
	"--clean",
	"--logout",
])("%s ignores unrelated malformed hooks without runtime enrollment, and removes the update notice hook", (flag) => {
	mkdirSync(join(home, ".codex"));
	mkdirSync(join(home, "empty-path"));
	const hooks = join(home, ".codex", "hooks.json");
	writeFileSync(hooks, "{unrelated malformed configuration");
	const claude = join(home, ".claude", "settings.json");
	mkdirSync(join(home, ".claude"));
	const keep = { hooks: [{ type: "command", command: "keep-this-hook" }] };
	const notice =
		"'node' 'launcher-v1.mjs' 'hook' 'notice' 'claude-code' --pharaoh-update-notice-v1";
	const feed = "'node' 'native-feed-hook.mjs' --client claude-code --pharaoh-native-feed-v1";
	writeJson(claude, {
		hooks: {
			SessionStart: [
				{ hooks: [notice, feed].map((command) => ({ type: "command", command })) },
				keep,
			],
		},
	});
	const result = cli([flag], { path: join(home, "empty-path") });
	expect(result.status, result.stderr).toBe(0);
	expect(result.stderr).not.toContain("runtime revocation");
	expect(readFileSync(hooks, "utf8")).toBe("{unrelated malformed configuration");
	expect(readJson(claude).hooks).toEqual({ SessionStart: [keep] });
});

it("native feed removal preserves unrelated malformed groups while removing its own handlers", () => {
	const path = join(home, "settings.json");
	const own = { type: "command", command: "'node' 'feed.mjs' --pharaoh-native-feed-v1" };
	const keep = { hooks: [{ type: "command", command: "keep-this-hook" }] };
	const malformed = { hooks: "preserve-unrelated-shape" };
	writeJson(path, {
		hooks: { SessionStart: [{ hooks: [own] }, keep, malformed], PostToolUse: "unrelated" },
	});
	syncNativeFeedHooks("claude-code", null, { home, settingsPath: path });
	expect(readJson(path)).toEqual({
		hooks: { SessionStart: [keep, malformed], PostToolUse: "unrelated" },
	});
});

it("change-review flags stay local, fail closed without an eligible install, and support disabling", () => {
	const missing = cli(["--enable-change-review"], { cwd: home });
	expect(missing.status).toBe(1);
	expect(missing.stderr).toContain("active, signed-in Claude Code memory hooks");
	expect(cli(["--disable-change-review"], { cwd: home }).status).toBe(0);
	const unsupported = cli(["--enable-change-review", "--client", "codex"], { cwd: home });
	expect(unsupported.status).not.toBe(0);
	expect(unsupported.stderr).toContain("supports Claude Code only");
});
