import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { diagnoseLocalSetup } from "../src/doctor.js";
import { hasClaude } from "../src/setup.js";
import { fetchLatestVersion, getPackageVersion, isNewerVersion } from "../src/version.js";

const PKG_ROOT = join(__dirname, "..");

describe("SC-2: package launch metadata is pinned to the running version", () => {
	let home: string;

	beforeEach(() => {
		home = mkdtempSync(join(tmpdir(), "pharaoh-setup-"));
		mkdirSync(join(home, ".claude"), { recursive: true });
	});

	afterEach(() => {
		vi.restoreAllMocks();
		rmSync(home, { recursive: true, force: true });
	});

	it("the shipped .mcp.json pins the same version (regenerated by `pnpm build`)", () => {
		const mcp = JSON.parse(readFileSync(join(PKG_ROOT, ".mcp.json"), "utf-8")) as {
			mcpServers: { pharaoh: { command: string; args: string[] } };
		};
		expect(mcp.mcpServers.pharaoh).toEqual({
			command: "npx",
			args: [`@pharaoh-so/mcp@${getPackageVersion()}`],
		});
	});

	// A manual registration pins what `--version` prints. Unhandled, the flag ran
	// setup: proxy mode on a pipe, and in a terminal a sign-in that deleted saved
	// credentials. PATH holds only node, so a regression reaches no `claude` CLI.
	it.each(["--version", "-v"])("%s prints the version and exits before setup", (flag) => {
		const tsx = createRequire(import.meta.url).resolve("tsx/cli");
		const res = spawnSync(process.execPath, [tsx, join(PKG_ROOT, "src", "index.ts"), flag], {
			input: "",
			encoding: "utf-8",
			timeout: 20_000,
			env: { HOME: home, PATH: dirname(process.execPath), PHARAOH_MCP_DISABLE_BROWSER: "1" },
		});
		const { version } = JSON.parse(readFileSync(join(PKG_ROOT, "package.json"), "utf-8"));

		expect(res.stdout).toBe(`${version}\n`);
		expect(res.status).toBe(0);
		expect(readdirSync(home)).toEqual([".claude"]);
	});

	it("--doctor stays offline and leaves credentials and settings untouched without inferring a client", () => {
		mkdirSync(join(home, ".pharaoh"));
		const credentials = join(home, ".pharaoh", "credentials.json");
		writeFileSync(credentials, "PRIVATE-CREDENTIAL-SENTINEL");
		writeFileSync(join(home, ".claude", "CLAUDE.md"), "PRIVATE-INSTRUCTION-SENTINEL");
		const tsx = createRequire(import.meta.url).resolve("tsx/cli");
		const result = spawnSync(
			process.execPath,
			[tsx, join(PKG_ROOT, "src", "index.ts"), "--doctor", "--server", "http://127.0.0.1:1"],
			{
				cwd: home,
				input: "",
				encoding: "utf8",
				timeout: 20_000,
				env: { HOME: home, PATH: dirname(process.execPath), PHARAOH_MCP_DISABLE_BROWSER: "1" },
			},
		);
		expect(result.status).toBe(0);
		expect(result.stderr).toBe("");
		expect(result.stdout).toContain("Client selection: unverified");
		expect(result.stdout).toContain("Project instruction marker: unknown");
		expect(result.stdout).not.toContain("SENTINEL");
		expect(readFileSync(credentials, "utf8")).toBe("PRIVATE-CREDENTIAL-SENTINEL");
		expect(readdirSync(home)).toEqual([".claude", ".pharaoh"]);
		const project = join(home, "repo");
		mkdirSync(join(project, ".git"), { recursive: true });
		writeFileSync(join(project, "CLAUDE.md"), "Ask Pharaoh before searching.");
		expect(diagnoseLocalSetup({ home, cwd: project, env: {} }).instructions.project).toBe(
			"unknown",
		);
		expect(
			diagnoseLocalSetup({ home, cwd: project, env: {}, clientName: "codex" }).instructions.project,
		).toBe("unknown");
		expect(
			diagnoseLocalSetup({ home, cwd: project, env: {}, clientName: "claude-code" }).instructions
				.project,
		).toBe("mention");
	});
});

describe("Claude CLI detection for optional plugin installation", () => {
	let home: string;
	const savedPath = process.env.PATH;

	beforeEach(() => {
		home = mkdtempSync(join(tmpdir(), "pharaoh-setup-no-cli-"));
		// The desktop app creates ~/.claude; only the CLI is missing.
		mkdirSync(join(home, ".claude"), { recursive: true });
		mkdirSync(join(home, "bin"));
		process.env.PATH = join(home, "bin");
	});

	afterEach(() => {
		process.env.PATH = savedPath;
		vi.restoreAllMocks();
		rmSync(home, { recursive: true, force: true });
	});

	it("reports an unavailable CLI without affecting direct configuration adapters", () => {
		expect(hasClaude()).toBe(false);
	});

	it.skipIf(process.platform === "win32")(
		"finds a claude that starts where there is no `which` (minimal containers)",
		() => {
			writeFileSync(join(home, "bin", "claude"), "#!/bin/sh\necho 2.0.0\n", { mode: 0o755 });

			expect(hasClaude()).toBe(true);
		},
	);

	// The CLAUDE.md line is the user's file: asked about only here, never on a proxy start.
	it("offers the agent instruction once, in the interactive setup after registration", () => {
		const main = readFileSync(join(PKG_ROOT, "src", "index.ts"), "utf-8");
		const interactive = main.slice(
			main.indexOf('await import("./install.js")'),
			main.indexOf("// ── Proxy mode"),
		);
		const at = (code: string) => interactive.indexOf(code);

		expect(main.match(/offerAgentInstructionLines\(/g)).toHaveLength(1);
		expect(at("runInstall({")).toBeLessThan(at("offerAgentInstructionLines("));
		expect(at("offerAgentInstructionLines(")).toBeGreaterThan(-1);
	});

	// uninstallClaudePlugin removes the CLAUDE.md line; on --logout it must not stand between the user and a credential wipe.
	it("--clean and --logout remove the CLAUDE.md line, and --logout deletes credentials first", () => {
		const main = readFileSync(join(PKG_ROOT, "src", "index.ts"), "utf-8");
		const branch = (opening: string) => {
			const start = main.indexOf(opening);
			return main.slice(start, main.indexOf("process.exit(0)", start));
		};
		expect(branch('if (args.includes("--clean")) {')).toContain("uninstallClaudePlugin();");
		const logout = branch("if (logout) {");
		expect(logout).toContain("uninstallClaudePlugin();");
		expect(logout).toContain("await takeCredentialsForLogout();");
		expect(logout.indexOf("await takeCredentialsForLogout();")).toBeLessThan(
			logout.indexOf("uninstallClaudePlugin();"),
		);
	});
});

describe("SC-9: package.json names the repository that builds it", () => {
	it("repository names the standalone public source, so npm provenance verifies", () => {
		const pkg = JSON.parse(readFileSync(join(PKG_ROOT, "package.json"), "utf-8")) as {
			repository: { type: string; url: string; directory?: string };
		};
		expect(pkg.repository).toEqual({
			type: "git",
			url: "git+https://github.com/Pharaoh-so/pharaoh-mcp.git",
		});
	});
});

describe("upgrade hint — version comparison and the registry check", () => {
	it.each([
		["0.3.44", "0.3.43", true],
		["0.4.0", "0.3.99", true],
		["1.0.0", "0.9.9", true],
		["0.3.43", "0.3.43", false],
		["0.3.42", "0.3.43", false],
		["garbage", "0.3.43", false],
	])("isNewerVersion(%s, %s) is %s", (candidate, current, expected) => {
		expect(isNewerVersion(candidate, current)).toBe(expected);
	});

	it("returns the registry's latest version", async () => {
		const fetchImpl = (async () => ({
			ok: true,
			json: async () => ({ version: "9.9.9" }),
		})) as unknown as typeof fetch;

		await expect(fetchLatestVersion(fetchImpl)).resolves.toBe("9.9.9");
	});

	it("returns null, without throwing, when the registry is unreachable or answers oddly", async () => {
		const offline = (async () => {
			throw new Error("ENOTFOUND");
		}) as unknown as typeof fetch;
		const odd = (async () => ({ ok: true, json: async () => ({}) })) as unknown as typeof fetch;

		await expect(fetchLatestVersion(offline)).resolves.toBeNull();
		await expect(fetchLatestVersion(odd)).resolves.toBeNull();
	});
});

it("explicit reset continues independent cleanup when the private installation record is broken", () => {
	const home = mkdtempSync(join(tmpdir(), "pharaoh-reset-broken-record-"));
	try {
		mkdirSync(join(home, ".pharaoh"));
		mkdirSync(join(home, "empty-path"));
		writeFileSync(join(home, ".pharaoh", "client-installations.json"), "{broken");
		writeFileSync(
			join(home, ".claude.json"),
			JSON.stringify({
				mcpServers: {
					pharaoh: { command: "npx", args: ["@pharaoh-so/mcp@0.3.50"] },
					other: { command: "keep-this-server" },
				},
				projects: { fixture: { disabledMcpServers: ["pharaoh", "other"] } },
			}),
		);
		const tsx = createRequire(import.meta.url).resolve("tsx/cli");
		const result = spawnSync(process.execPath, [tsx, join(PKG_ROOT, "src/index.ts"), "--clean"], {
			encoding: "utf8",
			timeout: 20_000,
			env: {
				HOME: home,
				USERPROFILE: home,
				PATH: join(home, "empty-path"),
				PHARAOH_MCP_DISABLE_BROWSER: "1",
			},
		});
		expect(result.status).toBe(1);
		expect(result.stderr).toContain("installation record could not be read");
		expect(JSON.parse(readFileSync(join(home, ".claude.json"), "utf8"))).toEqual({
			mcpServers: { other: { command: "keep-this-server" } },
			projects: { fixture: { disabledMcpServers: ["other"] } },
		});
	} finally {
		rmSync(home, { recursive: true, force: true });
	}
});

it.each([
	"--clean",
	"--logout",
])("%s ignores unrelated malformed hooks without runtime enrollment, and removes the update notice hook", (flag) => {
	const home = mkdtempSync(join(tmpdir(), "pharaoh-clean-without-runtime-"));
	try {
		const codex = join(home, ".codex");
		mkdirSync(codex);
		mkdirSync(join(home, "empty-path"));
		const hooks = join(codex, "hooks.json");
		writeFileSync(hooks, "{unrelated malformed configuration");
		const claude = join(home, ".claude", "settings.json");
		mkdirSync(join(home, ".claude"));
		const keep = { hooks: [{ type: "command", command: "keep-this-hook" }] };
		const notice =
			"'node' 'launcher-v1.mjs' 'hook' 'notice' 'claude-code' --pharaoh-update-notice-v1";
		writeFileSync(
			claude,
			JSON.stringify({
				hooks: { SessionStart: [{ hooks: [{ type: "command", command: notice }] }, keep] },
			}),
		);
		const tsx = createRequire(import.meta.url).resolve("tsx/cli");
		const result = spawnSync(process.execPath, [tsx, join(PKG_ROOT, "src/index.ts"), flag], {
			encoding: "utf8",
			timeout: 20_000,
			env: {
				HOME: home,
				USERPROFILE: home,
				PATH: join(home, "empty-path"),
				PHARAOH_MCP_DISABLE_BROWSER: "1",
			},
		});
		expect(result.status, result.stderr).toBe(0);
		expect(result.stderr).not.toContain("runtime revocation");
		expect(readFileSync(hooks, "utf8")).toBe("{unrelated malformed configuration");
		expect(JSON.parse(readFileSync(claude, "utf8")).hooks).toEqual({ SessionStart: [keep] });
	} finally {
		rmSync(home, { recursive: true, force: true });
	}
});
